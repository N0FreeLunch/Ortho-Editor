// d2item_rupture_oracle.rs -- Verification tool for analyzing ParserProbe trace outputs and ranking rupture points
// Belongs to Phase 6 Slice S3.2a tooling. Consumes fresh census JSON reports and computes diagnostic failure rankings.

use anyhow::{Context, Result};
use serde::Serialize;
use serde_json::Value;
use std::env;
use std::fs;
use std::path::PathBuf;
use std::process;

#[derive(Serialize, Debug)]
struct SchemaGateSummary {
    status: String,
    total_rows_inspected: usize,
    eligible_failure_count: usize,
    excluded_count: usize,
}

#[derive(Serialize, Debug)]
struct ExcludedRow {
    item_path: String,
    code: String,
    reason: String,
}

#[derive(Serialize, Debug, Clone)]
struct EligibleFailureRow {
    save_file: Option<String>,
    section: Option<String>,
    item_index: usize,
    item_path: String,
    code: String,
    bit_start: u64,
    bit_end: u64,
    failure_bit_offset_abs: u64,
    delta_to_retained_end: i64,
    nearest_accepted_boundary_delta: Option<i64>,
    terminal_segment_label: Option<String>,
    terminal_segment_depth: Option<u64>,
    failure_context_stack: Vec<String>,
    trace_segments: Vec<Value>,
}

#[derive(Serialize, Debug)]
struct RuptureOracleReport {
    schema_gate: SchemaGateSummary,
    excluded_rows: Vec<ExcludedRow>,
    eligible_failure_rows: Vec<EligibleFailureRow>,
    rupture_rows: Vec<EligibleFailureRow>,
}

fn select_deepest_containing_segment_impl<'a>(
    trace_segments: &'a [Value],
    candidate_start_bit: u64,
    failure_bit_offset_abs: u64,
) -> &'a Value {
    let mut selected_index = trace_segments.len() - 1;
    let mut selected_rank: Option<(u64, usize)> = None;

    for (source_order, seg) in trace_segments.iter().enumerate() {
        let start_rel = seg.get("start").and_then(|v| v.as_u64()).unwrap_or(0);
        let end_rel = seg.get("end").and_then(|v| v.as_u64()).unwrap_or(0);
        let seg_abs_start = candidate_start_bit + start_rel;
        let seg_abs_end = candidate_start_bit + end_rel;

        if failure_bit_offset_abs >= seg_abs_start && failure_bit_offset_abs <= seg_abs_end {
            let depth = seg.get("depth").and_then(|v| v.as_u64()).unwrap_or(0);
            let rank = (depth, source_order);
            if selected_rank.is_none_or(|current| rank > current) {
                selected_index = source_order;
                selected_rank = Some(rank);
            }
        }
    }

    &trace_segments[selected_index]
}

fn print_help() {
    println!("d2item_rupture_oracle -- Rupture ranking diagnostic tool for ParserProbe traces");
    println!();
    println!("USAGE:");
    println!(
        "    d2item_rupture_oracle --input <CENSUS_JSON_PATH> [--output <OUTPUT_JSON_PATH>] [--json] [--help]"
    );
    println!();
    println!("FLAGS:");
    println!("    --help       Display this help message and exit.");
    println!(
        "    --json       Format output as JSON on stdout (if --output is omitted or alongside output file)."
    );
    println!();
    println!("OPTIONS:");
    println!(
        "    --input <PATH>    Path to input census JSON report generated by d2item_opaque_census."
    );
    println!("    --output <PATH>   Path to output JSON file to write oracle ranking report.");
}

fn main() -> Result<()> {
    let args: Vec<String> = env::args().collect();

    if args.iter().any(|arg| arg == "--help" || arg == "-h") {
        print_help();
        process::exit(0);
    }

    let mut input_path: Option<PathBuf> = None;
    let mut output_path: Option<PathBuf> = None;
    let mut json_flag = false;

    let mut i = 1;
    while i < args.len() {
        match args[i].as_str() {
            "--input" => {
                if i + 1 < args.len() {
                    input_path = Some(PathBuf::from(&args[i + 1]));
                    i += 1;
                } else {
                    eprintln!("Error: --input requires a path argument.");
                    process::exit(1);
                }
            }
            "--output" => {
                if i + 1 < args.len() {
                    output_path = Some(PathBuf::from(&args[i + 1]));
                    i += 1;
                } else {
                    eprintln!("Error: --output requires a path argument.");
                    process::exit(1);
                }
            }
            "--json" => {
                json_flag = true;
            }
            _ => {
                // Ignore unexpected or positional arguments gracefully if valid input is passed
            }
        }
        i += 1;
    }

    let input_file = match input_path {
        Some(path) => path,
        None => {
            eprintln!("Error: Missing required argument --input <PATH>.");
            print_help();
            process::exit(1);
        }
    };

    let content = fs::read_to_string(&input_file)
        .with_context(|| format!("Failed to read input census JSON from {:?}", input_file))?;

    let root: Value = serde_json::from_str(&content)
        .with_context(|| format!("Failed to parse JSON content from {:?}", input_file))?;

    let rows_val = root
        .get("rows")
        .and_then(|v| v.as_array())
        .with_context(|| "Input JSON does not contain a valid 'rows' array.")?;

    let total_rows_inspected = rows_val.len();
    let mut excluded_rows: Vec<ExcludedRow> = Vec::new();
    let mut eligible_failure_rows: Vec<EligibleFailureRow> = Vec::new();

    for row in rows_val {
        let item_path = row
            .get("item_path")
            .and_then(|v| v.as_str())
            .unwrap_or("unknown")
            .to_string();
        let code = row
            .get("code")
            .and_then(|v| v.as_str())
            .unwrap_or("???")
            .to_string();
        let save_file = row
            .get("save_file")
            .and_then(|v| v.as_str())
            .map(|s| s.to_string());
        let section = row
            .get("section")
            .and_then(|v| v.as_str())
            .map(|s| s.to_string());
        let item_index = row.get("item_index").and_then(|v| v.as_u64()).unwrap_or(0) as usize;
        let bit_start = row.get("bit_start").and_then(|v| v.as_u64()).unwrap_or(0);
        let bit_end = row.get("bit_end").and_then(|v| v.as_u64()).unwrap_or(0);

        let probe = match row.get("parser_probe") {
            Some(p) if !p.is_null() => p,
            _ => {
                excluded_rows.push(ExcludedRow {
                    item_path,
                    code,
                    reason: "missing_parser_probe".to_string(),
                });
                continue;
            }
        };

        let candidate_start_bit = probe.get("candidate_start_bit").and_then(|v| v.as_u64());
        let candidate_limit_bits = probe.get("candidate_limit_bits").and_then(|v| v.as_u64());
        let outcome = probe.get("outcome").and_then(|v| v.as_str());
        let failure_bit_offset_abs = probe.get("failure_bit_offset_abs").and_then(|v| v.as_u64());

        // Enforce schema gate: candidate_start_bit + candidate_limit_bits == bit_end
        if let (Some(start), Some(limit)) = (candidate_start_bit, candidate_limit_bits) {
            if start.saturating_add(limit) != bit_end {
                excluded_rows.push(ExcludedRow {
                    item_path,
                    code,
                    reason: "schema_gate_mismatch".to_string(),
                });
                continue;
            }
        } else {
            excluded_rows.push(ExcludedRow {
                item_path,
                code,
                reason: "incomplete_coordinate_schema".to_string(),
            });
            continue;
        }

        if outcome != Some("parse_failure") {
            excluded_rows.push(ExcludedRow {
                item_path,
                code,
                reason: "not_parse_failure".to_string(),
            });
            continue;
        }

        let fail_offset = match failure_bit_offset_abs {
            Some(offset) => offset,
            None => {
                excluded_rows.push(ExcludedRow {
                    item_path,
                    code,
                    reason: "missing_failure_offset".to_string(),
                });
                continue;
            }
        };

        let delta_to_retained_end = fail_offset as i64 - bit_end as i64;

        // Nearest accepted boundary candidate delta calculation
        let nearest_accepted_boundary_delta = row
            .get("boundary_candidates")
            .and_then(|bc| bc.as_array())
            .map(|candidates| {
                candidates
                    .iter()
                    .filter(|c| c.get("status").and_then(|s| s.as_str()) == Some("accepted"))
                    .filter_map(|c| c.get("absolute_bit_position").and_then(|p| p.as_u64()))
                    .map(|cand_pos| fail_offset as i64 - cand_pos as i64)
                    .min_by_key(|delta| delta.abs())
            })
            .flatten();

        // Trace segments extraction and terminal segment finding
        let trace_segments = probe
            .get("trace_segments")
            .and_then(|v| v.as_array())
            .cloned()
            .unwrap_or_default();

        let mut terminal_segment_label: Option<String> = None;
        let mut terminal_segment_depth: Option<u64> = None;

        if !trace_segments.is_empty() {
            let candidate_start = candidate_start_bit.unwrap_or(0);
            let selected = select_deepest_containing_segment_impl(
                &trace_segments,
                candidate_start,
                fail_offset,
            );
            terminal_segment_label = selected
                .get("label")
                .and_then(|v| v.as_str())
                .map(|s| s.to_string());
            terminal_segment_depth = selected.get("depth").and_then(|v| v.as_u64());
        }

        let failure_context_stack = probe
            .get("failure_context_stack")
            .and_then(|v| v.as_array())
            .map(|arr| {
                arr.iter()
                    .filter_map(|v| v.as_str().map(|s| s.to_string()))
                    .collect()
            })
            .unwrap_or_default();

        eligible_failure_rows.push(EligibleFailureRow {
            save_file,
            section,
            item_index,
            item_path,
            code,
            bit_start,
            bit_end,
            failure_bit_offset_abs: fail_offset,
            delta_to_retained_end,
            nearest_accepted_boundary_delta,
            terminal_segment_label,
            terminal_segment_depth,
            failure_context_stack,
            trace_segments,
        });
    }

    // Rank eligible failure rows deterministically
    let mut rupture_rows = eligible_failure_rows.clone();
    rupture_rows.sort_by(|a, b| {
        a.delta_to_retained_end
            .abs()
            .cmp(&b.delta_to_retained_end.abs())
            .then_with(|| {
                a.nearest_accepted_boundary_delta
                    .map(|d| d.abs())
                    .unwrap_or(i64::MAX)
                    .cmp(
                        &b.nearest_accepted_boundary_delta
                            .map(|d| d.abs())
                            .unwrap_or(i64::MAX),
                    )
            })
            .then_with(|| a.item_path.cmp(&b.item_path))
            .then_with(|| a.item_index.cmp(&b.item_index))
    });

    let schema_gate = SchemaGateSummary {
        status: if excluded_rows
            .iter()
            .any(|r| r.reason == "schema_gate_mismatch")
        {
            "warning_schema_mismatch".to_string()
        } else {
            "passed".to_string()
        },
        total_rows_inspected,
        eligible_failure_count: eligible_failure_rows.len(),
        excluded_count: excluded_rows.len(),
    };

    let report = RuptureOracleReport {
        schema_gate,
        excluded_rows,
        eligible_failure_rows,
        rupture_rows,
    };

    let report_json = serde_json::to_string_pretty(&report)
        .context("Failed to serialize RuptureOracleReport to JSON")?;

    if let Some(ref out_path) = output_path {
        if let Some(parent) = out_path.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::write(out_path, &report_json)
            .with_context(|| format!("Failed to write output JSON report to {:?}", out_path))?;
        println!("Oracle report successfully written to {:?}", out_path);
    }

    if json_flag || output_path.is_none() {
        println!("{}", report_json);
    }

    Ok(())
}

#[cfg(test)]
#[test]
fn select_deepest_containing_segment() {
    let trace_segments = vec![
        serde_json::json!({"start": 0, "end": 149, "label": "Root", "depth": 0}),
        serde_json::json!({"start": 0, "end": 149, "label": "ExtendedStats", "depth": 1}),
        serde_json::json!({"start": 0, "end": 149, "label": "ExtendedStats:id", "depth": 2}),
    ];

    let selected = select_deepest_containing_segment_impl(&trace_segments, 8752, 8901);
    assert_eq!(
        selected.get("label").and_then(|v| v.as_str()),
        Some("ExtendedStats:id")
    );
    assert_eq!(selected.get("depth").and_then(|v| v.as_u64()), Some(2));

    let equal_depth_segments = vec![
        serde_json::json!({"start": 0, "end": 10, "label": "first", "depth": 1}),
        serde_json::json!({"start": 0, "end": 10, "label": "last", "depth": 1}),
    ];
    let selected = select_deepest_containing_segment_impl(&equal_depth_segments, 100, 110);
    assert_eq!(selected.get("label").and_then(|v| v.as_str()), Some("last"));

    let fallback_segments = vec![
        serde_json::json!({"start": 0, "end": 5, "label": "first", "depth": 0}),
        serde_json::json!({"start": 6, "end": 10, "label": "last", "depth": 1}),
    ];
    let selected = select_deepest_containing_segment_impl(&fallback_segments, 100, 150);
    assert_eq!(selected.get("label").and_then(|v| v.as_str()), Some("last"));
}
